# Sticky sash window assets. Metres, kilograms, Z up. Frame frame: origin on the table at the middle of the window (y) and on the
# front sash lane's middle (x); thickness along x, width along y.
#   window_frame.usda : fixed. Sill 40 mm high with a 12 mm lane wall either side of each glazing lane, header with lane walls, two
#                       jambs (the left one is the sash's end stop), a fixed pane (4 mm glass in a slim frame) in the back lane.
#   sash.usda         : one articulation with a free root: the sliding sash (250 x 270 x 20 mm pine frame, 4 mm glass, 1.5 kg) and a
#                       plastic pull tab on a spring hinge (Handle, axis Z). Origin: the middle of the sash's bottom edge.
# ======================================================================================================================
SILL_H = 0.040
LANE_X = 0.011  # half width of the sash lane (sash 20 mm thick: 1 mm a side)
WALL_T = 0.006
LIP_H = 0.012
OPEN_HALF = 0.240  # the window opening's half width
JAMB_T = 0.050
SASH_W, SASH_H, SASH_T = 0.250, 0.270, 0.020
STILE, RAIL_B, RAIL_T = 0.038, 0.055, 0.038
SASH_MASS = 1.5
MU = 0.40
TAB_HINGE = (-0.010, 0.080, 0.030)  # in the sash frame
TAB_L, TAB_W, TAB_H = 0.036, 0.010, 0.020
TAB_K = 0.80  # N m / rad
HEADER_Z = SILL_H + SASH_H + 0.004


def frame(fname):
    a = Asset(fname, "WindowFrame", "A shed or greenhouse sliding window frame in a 40 mm sill: opening 480 x 270 mm, a 22 mm sash lane (front) and a "
              "fixed pane (back), lane walls 6 mm thick, a header, two jambs; the left jamb (+y) is the sash's end stop. Fixed. Origin: table "
              "level, the opening's middle in y, the front lane's middle in x.", 5.0)
    pine = (0.78, 0.62, 0.40)
    f = (MU, MU)
    xs = (-LANE_X - WALL_T / 2, LANE_X + WALL_T / 2, 0.036 + WALL_T / 2)
    a.box((0, 0, SILL_H / 2), (0.090, 2 * (OPEN_HALF + JAMB_T), SILL_H), pine, f, key="wood", name="Sill")
    for x in xs:
        a.box((x, 0, SILL_H + LIP_H / 2), (WALL_T, 2 * OPEN_HALF, LIP_H), pine, f, key="wood", name="Lip")
        a.box((x, 0, HEADER_Z - 0.007), (WALL_T, 2 * OPEN_HALF, 0.014), pine, f, key="wood", name="HeadWall")
    a.box((0, 0, HEADER_Z + 0.010), (0.090, 2 * (OPEN_HALF + JAMB_T), 0.020), pine, f, key="wood", name="Header")
    for s in (-1, 1):
        a.box((0, s * (OPEN_HALF + JAMB_T / 2), (SILL_H + HEADER_Z + 0.020) / 2), (0.090, JAMB_T, HEADER_Z + 0.020 - SILL_H), pine, f, key="wood", name="Jamb")
    a.box((0.0235, -OPEN_HALF / 2, SILL_H + SASH_H / 2), (0.004, OPEN_HALF - 0.002, SASH_H - 0.004), (0.70, 0.85, 0.90), f, key="wood", name="FixedGlass")
    a.mass_props(5.0, (0, 0, 0.1), (0.05, 0.05, 0.05))
    a.save()


def sash(fname):
    a = Asset(fname, "Sash", "A sliding sash for a shed or greenhouse window: pine frame 250 x 270 x 20 mm (stiles 38 mm, bottom rail 55 mm, top rail 38 mm), "
              "4 mm glass, 1.5 kg, and a plastic pull tab (36 x 10 x 20 mm) on a spring hinge (joint Handle, axis Z, 0.8 N m/rad). Free root. Origin: "
              "the middle of the sash's bottom edge; thickness along x.", SASH_MASS)
    pine = (0.82, 0.68, 0.45)
    f = (MU, MU)
    g = (0.3, 0.3)
    t = (0.5, 0.45)
    a.box((0, SASH_W / 2 - STILE / 2, SASH_H / 2), (SASH_T, STILE, SASH_H), pine, f, key="wood", name="StileL")
    a.box((0, -SASH_W / 2 + STILE / 2, SASH_H / 2), (SASH_T, STILE, SASH_H), pine, f, key="wood", name="StileR")
    a.box((0, 0, RAIL_B / 2), (SASH_T, SASH_W - 2 * STILE, RAIL_B), pine, f, key="wood", name="RailB")
    a.box((0, 0, SASH_H - RAIL_T / 2), (SASH_T, SASH_W - 2 * STILE, RAIL_T), pine, f, key="wood", name="RailT")
    a.box((0, 0, (RAIL_B + SASH_H - RAIL_T) / 2), (0.004, SASH_W - 2 * STILE + 0.004, SASH_H - RAIL_B - RAIL_T + 0.004), (0.70, 0.85, 0.90), g, key="glass", name="Glass")
    a.mass_props(SASH_MASS, (0, 0, SASH_H / 2), box_inertia(SASH_MASS, SASH_T, SASH_W, SASH_H))
    a.articulation_root()
    m = 0.005
    tab = a.link("Tab", m, com=(-TAB_L / 2, 0, 0), inertia=box_inertia(m, TAB_L, TAB_W, TAB_H), pos=TAB_HINGE)
    a.box((-TAB_L / 2, 0, 0), (TAB_L, TAB_W, TAB_H), (0.20, 0.45, 0.80), t, key="tab", name="TabBody")
    a.revolute("Handle", a.root.GetPrim(), tab, axis="Z", lo=-25.0, hi=25.0, stiffness=TAB_K * math.pi / 180.0,
               damping=0.004 * math.pi / 180.0, target=0.0, p0=TAB_HINGE, p1=(0, 0, 0))
    a.save()


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    frame("window_frame.usda")
    sash("sash.usda")
