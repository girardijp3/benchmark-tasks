# Brush-roll task assets. Metres, kilograms, Z up. The roll's axis runs along y.
#   roll.usda    : a robot vacuum's brush roll, one rigid body (0.10 kg): a 28 mm x 200 mm body, a round stub (11 mm across, 18 mm long)
#                  at its -y end and a square drive stub (8 x 8 mm, 18 mm long) at its +y end. Origin: the body's middle, axis along y.
#   chassis.usda : the brush bay of the vacuum as one fixed articulation: a base plate, two end walls 14 mm thick (inner faces 108 mm from
#                  the middle) with U-slots open at the top: a 12 mm bearing slot in the -y wall and a 9.5 mm square drive socket in the
#                  +y wall (floors 20.5 and 22 mm up; 45 degree V lead-ins from 30 mm up to 52 mm wide at the top, 50 mm up), and a drive-end
#                  retainer clip (link Retainer: a 34 x 30 mm flap hinged on an ear outside the +y wall, revolute about x, 0 degrees closed over the
#                  drive socket, -75 degrees open (the flap points toward -y), sprung open). Origin: table level, the bay's middle (x 0, y 0).
# ======================================================================================================================
BODY_R, BODY_L = 0.014, 0.200
STUB_L = 0.018
ROUND_R, SQ_HALF = 0.0055, 0.004
AXIS_Z = 0.026  # the roll's axis above the table when seated
WALL_IN, WALL_OUT = 0.108, 0.122
WALL_TOP = 0.050
BASE_T = 0.010
SLOT_FLOOR = {"bearing": AXIS_Z - ROUND_R, "drive": AXIS_Z - SQ_HALF}
SLOT_HALF = {"bearing": 0.006, "drive": 0.00475}
HINGE = (0.0, WALL_OUT + 0.004, 0.0515)  # the retainer's hinge on its ear outside the +y wall
GUARD_L, GUARD_W, GUARD_T = 0.030, 0.034, 0.003
OPEN_DEG = 75.0
K_GUARD, D_GUARD = 0.01, 0.0005


def roll(fname):
    m = 0.10
    a = Asset(fname, "Roll", "A robot vacuum's brush roll, 0.10 kg: a 28 x 200 mm body, a round stub (11 mm across, 18 mm long) at the -y end and a square drive "
              "stub (8 x 8 mm, 18 mm long) at the +y end. Origin: the body's middle, axis along y.", m, com=(0, 0, 0),
              inertia=(m / 12 * (3 * BODY_R**2 + BODY_L**2), m * BODY_R**2 / 2, m / 12 * (3 * BODY_R**2 + BODY_L**2)))
    f = (0.45, 0.40)
    a.cyl((0, 0, 0), BODY_R, BODY_L, "Y", (0.15, 0.15, 0.17), f, key="plastic", name="Body")
    a.cyl((0, -(BODY_L + STUB_L) / 2, 0), ROUND_R, STUB_L, "Y", (0.80, 0.80, 0.82), f, key="steel", name="RoundStub")
    a.box((0, (BODY_L + STUB_L) / 2, 0), (2 * SQ_HALF, STUB_L, 2 * SQ_HALF), (0.80, 0.30, 0.10), f, key="steel", name="SquareStub")
    a.save()


def _wall(a, sign, kind, rgb, f):
    floor, hw = SLOT_FLOOR[kind], SLOT_HALF[kind]
    y0, y1 = sorted((sign * WALL_IN, sign * WALL_OUT))
    hx = 0.040
    a.prism_y([(-hx, BASE_T), (hx, BASE_T), (hx, floor), (-hx, floor)], y0, y1, rgb, f, key="plastic", name="WallLow")
    for sg in (-1, 1):  # the sides of the slot: straight to 30 mm up, then a 45 degree V funnel to the top
        pts = [(sg * hw, floor), (sg * hx, floor), (sg * hx, WALL_TOP), (sg * (hw + WALL_TOP - 0.030), WALL_TOP), (sg * hw, 0.030)]
        a.prism_y(pts, y0, y1, rgb, f, key="plastic", name="WallSide")


def chassis(fname):
    a = Asset(fname, "Chassis", "A vacuum's brush bay: base plate, two end walls with U-slots (12 mm bearing slot at -y, 9.5 mm square drive socket at +y, stair lead-ins), "
              "a back wall and a sprung guard (revolute about y, 0 closed, 70 open). Origin: table level, the bay's middle.", 3.0, body=False)
    base = a.link("Base", 3.0, com=(0, 0, 0.01), inertia=(1e-2, 1e-2, 1e-2))  # the fixed articulation root: a rigid link, not the root Xform
    a.base_prim = base
    UsdPhysics.ArticulationRootAPI.Apply(base)
    body = (0.78, 0.78, 0.80)
    f = (0.45, 0.40)
    a.box((0, 0, BASE_T / 2), (0.090, 2 * WALL_OUT, BASE_T), body, f, key="plastic", name="Base")
    _wall(a, -1, "bearing", body, f)
    _wall(a, 1, "drive", body, f)
    a.box((0.0, HINGE[1] + 0.002, (BASE_T + HINGE[2]) / 2), (0.040, 0.008, HINGE[2] - BASE_T), body, f, key="plastic", name="Ear")
    root = base
    lk = a.link("Retainer", 0.008, com=(0, -GUARD_L / 2, 0), inertia=(1e-6, 1e-6, 1e-6), pos=HINGE)
    red = (0.75, 0.12, 0.10)
    a.box((0, -GUARD_L / 2, 0), (GUARD_W, GUARD_L, GUARD_T), red, f, key="plastic", name="Flap")
    a.cyl((0, 0, 0), 0.0025, 0.040, "X", (0.3, 0.3, 0.32), None, key="plastic", name="Pin")
    a.revolute("Retainer", root, lk, "X", lo=-(OPEN_DEG + 2.0), hi=1.0, stiffness=K_GUARD * math.pi / 180, damping=D_GUARD * math.pi / 180,
               target=-OPEN_DEG, p0=HINGE, p1=(0, 0, 0))  # the joint angle is negative when open (the flap points toward -y)
    a.save()


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    roll("roll.usda")
    chassis("chassis.usda")
